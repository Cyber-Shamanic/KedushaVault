    shade_paragraph(p, fill=LIGHT_BLUE, border=BLUE)
    doc.add_page_break()
    for ch in CHAPTERS:
        add_chapter_summary(doc, ch)
    add_anthology(doc)
    add_synthesis(doc, now)

    # Remove the final empty page-break paragraph if present.
    if doc.paragraphs and not doc.paragraphs[-1].text and doc.paragraphs[-1]._p.xpath('.//w:br[@w:type="page"]'):
        p = doc.paragraphs[-1]._element
        p.getparent().remove(p)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    doc.save(OUTPUT)
    return OUTPUT


