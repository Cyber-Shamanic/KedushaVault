def build() -> Path:
    now = datetime.now(ZoneInfo("Asia/Jerusalem"))
    doc = Document()
    configure_styles(doc)
    add_numbering(doc)
    configure_sections(doc)
    add_core_properties(doc, now)
    add_cover(doc, now)
    add_front_matter(doc)

    add_text(doc, "חלק ראשון", size=10, color=GOLD, bold=True, after=12, align=WD_ALIGN_PARAGRAPH.CENTER)
    add_text(doc, "סִכּוּם מָלֵא לְכָל פֶּרֶק", size=27, color=NAVY, bold=True, after=8, align=WD_ALIGN_PARAGRAPH.CENTER)
    add_text(doc, "16 שערים — מהלך, צירי תוכן ויישום", size=13.5, color=BLUE, bold=True, after=24, align=WD_ALIGN_PARAGRAPH.CENTER)
